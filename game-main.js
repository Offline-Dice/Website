async function getWorkerColorResults(count) {
    const uid = String(localStorage.getItem("offlineDiceFirebaseUserId") || "");
    const clientSeed = String(
        window.provablyFair?.clientSeed ||
        localStorage.getItem("clientSeed") ||
        "Kenzy"
    ).slice(0, 128);

    const nonce = Number.isSafeInteger(window.provablyFair?.nonce)
        ? window.provablyFair.nonce
        : 0;

    const headers = {
        "Content-Type": "application/json"
    };
    if (/^[A-Za-z0-9_-]{1,128}$/.test(uid)) {
        headers["X-Session"] = uid;
    }

    const response = await fetch(DICE_WORKER_URL, {
        method: "POST",
        headers,
        cache: "no-store",
        body: JSON.stringify({
            mode: "color",
            count: Math.max(1, Math.min(6, Number(count) || 1)),
            clientSeed,
            nonce
        })
    });

    if (!response.ok) {
        throw new Error("Dice Worker request failed (" + response.status + ")");
    }

    const data = await response.json();
    if (!data || !Array.isArray(data.results)) {
        throw new Error("Invalid Dice Worker response");
    }

    const colors = data.results.map(item => {
        const index = Number(item?.index);
        if (!Number.isInteger(index) || index < 0 || index >= validColors.length) {
            throw new Error("Invalid color index from Dice Worker");
        }
        return validColors[index];
    });

    // Verify Code is authoritative and generated by the Cloudflare Worker.
    if (typeof data.verifyCode !== "string" || !/^KZ-[A-Z0-9]{6}$/.test(data.verifyCode)) {
        throw new Error("Invalid Verify Code from Dice Worker");
    }
    if (window.provablyFair) {
        window.provablyFair.lastVerify = data.verifyCode;

        // Always put the fresh Worker Verify Code into the visible Verify box.
        // This prevents the placeholder text from remaining after a successful roll.
        const verifyDisplay = document.getElementById("verifyCodeDisplay");
        if (verifyDisplay) {
            verifyDisplay.textContent = data.verifyCode;
        }

        if (Number.isSafeInteger(data.nextNonce)) {
            window.provablyFair.nonce = data.nextNonce;
        } else {
            window.provablyFair.nonce = nonce + colors.length;
        }
        if (data.serverSeedHash) {
            window.provablyFair.lastHash = String(data.serverSeedHash);
        }
        const nonceEl = document.getElementById("nonceValue");
        if (nonceEl) nonceEl.textContent = window.provablyFair.nonce;
    }

    return colors;
}

