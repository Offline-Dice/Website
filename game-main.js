        function playDiceRollSound() {
            if (isMuted) return Promise.resolve();

            // Nur Halloween verwendet den Halloween-Sound. Die ursprüngliche
            // Roll-Dauer bleibt für alle Hintergründe gleich wie vorher.
            const themeSelect = document.getElementById("themeSelect");
            const activeSound = themeSelect && themeSelect.value === "halloween"
                ? halloweenDiceRollSound
                : diceRollSound;

            try { activeSound.currentTime = 0; } catch (e) {}

            return new Promise(resolve => {
                let finished = false;
                let timer = null;

                const finish = () => {
                    if (finished) return;
                    finished = true;
                    if (timer) clearTimeout(timer);
                    activeSound.removeEventListener("ended", finish);
                    resolve();
                };

                activeSound.addEventListener("ended", finish, { once: true });

                // Match the original timing cap so no theme makes the dice roll longer.
                const fallback = Number.isFinite(activeSound.duration) && activeSound.duration > 0
                    ? Math.min(activeSound.duration * 1000 + 40, 1400)
                    : 1000;
                timer = setTimeout(finish, fallback);

                activeSound.play().catch(e => {
                    console.log("Audio Error:", e);
                    finish();
                });
            });
        }

